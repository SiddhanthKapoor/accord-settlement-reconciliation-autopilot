def test_a_dataset_batch_still_reports_progress_it_can_prove(client):
    """`/batch/run` does not go through the run executor at all.

    It records no phase, so progress has to be derived from the batch
    row alone — and must still be truthful rather than empty.
    """
    batch = client.post("/batch/run", json={"dataset": "dev", "limit": 5}).json()
    batch_id = batch["batch_id"]

    deadline = time.time() + 120
    while time.time() < deadline:
        progress = client.get(f"/runs/{batch_id}/progress").json()
        if progress["complete"]:
            break
        assert STAGE_ORDER[progress["stage"]] >= STAGE_ORDER["DETERMINISTIC"]
        time.sleep(0.05)
    else:
        raise AssertionError("dataset batch did not complete in time")

    assert progress["stage"] == "COMPLETE"
    assert progress["processed"] == progress["total"] == batch["total_records"]
    # It has no sources, so it never inspected any, and says so.
    inspecting = progress["stages"][0]
    assert inspecting["count"] is None and inspecting["total"] is None


def _finish(client, run_id) -> dict:
    confirm_everything(client, run_id)
    response = client.post(f"/runs/{run_id}/execute", json={})
    assert response.status_code == 200, response.text
    return run_to_completion(client, run_id)[-1]


def test_an_offline_run_never_claims_a_model_was_consulted(client, tmp_path, monkeypatch):
    """The regression this whole split exists to prevent.

    `ai_invoked` on a record means "the semantic tier was reached". With
    no provider configured, the offline heuristic serves that tier — and
    a summary that reads "AI consulted: 1" off that column would be
    telling a viewer a model was used when none was called. The tier
    total is still reported, under a name that says what it is.
    """
    monkeypatch.setattr(runs_api, "DEMO_WORKSPACE_DIR", ambiguous_workspace(tmp_path))
    run_id = client.post("/runs/sample", json={}).json()["run_id"]
    final = _finish(client, run_id)

    assert final["semantic_tier_invoked"] > 0, "the fixture must reach the semantic tier"
    assert final["ai_consulted"] == 0, "no provider was called, so nothing was consulted"
    assert final["heuristic_consulted"] == final["semantic_tier_invoked"]
    assert final["semantic_backend"] == "heuristic"

    records = client.get(f"/batch/{run_id}/records?limit=1000").json()
    invoked = [r for r in records if r["ai_invoked"]]
    assert invoked and all("heuristic" in (r["ai_backend"] or "") for r in invoked)

    investigating = {s["key"]: s for s in final["stages"]}["INVESTIGATING"]
    assert investigating["count"] == 0
    assert "no model was called" in investigating["detail"]
    assert str(final["semantic_tier_invoked"]) in investigating["detail"]

    # And the headline must never have promoted this run to INVESTIGATING.
    from app.ledger import store
