def test_progress_reports_null_for_what_is_not_yet_known(client):
    """A run that has not been executed has not measured anything.

    `null`, not zero. A zero on a progress display is indistinguishable
    from a measurement of nothing, and a reader would be right to treat
    it as one.
    """
    run_id = client.post("/runs", json={"label": "empty"}).json()["run_id"]
    progress = client.get(f"/runs/{run_id}/progress").json()

    assert progress["started"] is False
    assert progress["complete"] is False
    assert progress["total"] is None, "the size of an unexecuted run is not known"
    assert progress["processed"] == 0
    assert progress["error"] is None
    assert progress["updated_at"] is None

    assert progress["semantic_backend"] is None, "nothing has served a tier nothing reached"
    assert progress["semantic_tier_invoked"] == 0
    assert progress["ai_consulted"] == 0

    assert [s["state"] for s in progress["stages"]] == ["PENDING"] * 5
    for stage in progress["stages"]:
        assert stage["count"] is None, f"{stage['key']} reported a count before it ran"
        assert stage["total"] is None, f"{stage['key']} reported a total before it ran"


def test_progress_advances_through_the_real_stages_and_reaches_complete(client):
    """Stage state tracks execution, and never goes backwards."""
    files = workspace_files()
    assert files

    sample = client.post("/runs/sample", json={}).json()
    run_id = sample["run_id"]
    confirm_everything(client, run_id)

    before = client.get(f"/runs/{run_id}/progress").json()
    assert before["stage"] == "INSPECTING" and before["started"] is False

    execute = client.post(f"/runs/{run_id}/execute", json={})
    assert execute.status_code == 200, execute.text
    summary = execute.json()

    snapshots = run_to_completion(client, run_id)
    observed = [p["stage"] for p in snapshots]
    positions = [STAGE_ORDER[s] for s in observed]
    assert positions == sorted(positions), f"progress went backwards: {observed}"
    assert observed[-1] == "COMPLETE"

    # Reading, mapping and normalising happen before /execute returns, so
    # by the first poll they are genuinely finished — and they report the
    # counts the executor actually recorded, not a stand-in.
    final = snapshots[-1]
    stages = {s["key"]: s for s in final["stages"]}
    assert [s["state"] for s in final["stages"]] == ["DONE"] * 5

    assert stages["INSPECTING"]["count"] == len(files)
    assert stages["INSPECTING"]["total"] == len(files)
    assert stages["NORMALISING"]["count"] == (
        summary["ledger_records"] + summary["settlement_records"]
    )
    assert stages["DETERMINISTIC"]["total"] == summary["total_records"]
    assert stages["DETERMINISTIC"]["count"] == summary["total_records"]

    assert final["processed"] == final["total"] == summary["total_records"]
    assert final["complete"] is True
    assert final["error"] is None

    # Every stage that advanced during the run reported a count from the
    # store, so the panel can never show a step that "ran" with nothing
    # behind it.
    assert stages["INVESTIGATING"]["count"] == final["ai_consulted"]
    assert stages["REVIEW"]["count"] == final["unresolved"]


def test_progress_counts_agree_with_the_records_they_describe(client):
    """ai_consulted and unresolved are counted, not asserted."""
    sample = client.post("/runs/sample", json={}).json()
    run_id = sample["run_id"]
    confirm_everything(client, run_id)
    assert client.post(f"/runs/{run_id}/execute", json={}).status_code == 200
    final = run_to_completion(client, run_id)[-1]

    records = client.get(f"/batch/{run_id}/records?limit=100000").json()
    assert len(records) == final["total"]
    assert final["unresolved"] == sum(1 for r in records if r["outcome"] == "HUMAN_REVIEW")

    def served_by_a_model(record):
        backend = (record["ai_backend"] or "").lower()
        return bool(record["ai_invoked"] and backend and "heuristic" not in backend)

    assert final["semantic_tier_invoked"] == sum(1 for r in records if r["ai_invoked"])
    assert final["ai_consulted"] == sum(1 for r in records if served_by_a_model(r))
    assert final["heuristic_consulted"] == sum(
        1 for r in records if r["ai_invoked"] and "heuristic" in (r["ai_backend"] or "").lower()
    )
    assert final["ai_consulted"] <= final["semantic_tier_invoked"]
    assert final["stage"] == "COMPLETE"


def test_the_deciding_headline_names_what_the_pass_is_actually_doing(client):
    """DETERMINISTIC and INVESTIGATING are one pass, named honestly.

    The engine consults the model *inside* the matching loop, on the
    record whose evidence turned out to be ambiguous — there is no
    separate investigation phase to report. So the headline says
    INVESTIGATING only once a consultation has actually happened on this
    run, and both rows advance together rather than one after the other.

    Driven by rewinding the stored phase to the one the executor writes
    while the loop is running, because a finished offline run is over
    before a poller can see the middle of it.
    """
    from app.ledger import store

    sample = client.post("/runs/sample", json={}).json()
    run_id = sample["run_id"]
    confirm_everything(client, run_id)
    assert client.post(f"/runs/{run_id}/execute", json={}).status_code == 200
    final = run_to_completion(client, run_id)[-1]

    store.update_run_progress(run_id, phase=runs_api.PHASE_DECIDING)
    # The batch row is the authority on completion, so it has to be moved
    # back too or the recorded phase is correctly overruled.
    store.get_conn().execute("UPDATE batches SET status='RUNNING' WHERE batch_id=?", (run_id,))

    mid = client.get(f"/runs/{run_id}/progress").json()
    if final["ai_consulted"] > 0:
        assert mid["stage"] == "INVESTIGATING" and mid["ai_consulted"] > 0
    else:
        assert mid["stage"] == "DETERMINISTIC", (
            "nothing was investigated, so the headline must not claim it was"
        )
    states = {s["key"]: s["state"] for s in mid["stages"]}
    assert states["DETERMINISTIC"] == states["INVESTIGATING"] == "ACTIVE", (
        "matching and investigation are interleaved; neither finishes before the other starts"
    )
    assert states["REVIEW"] == "ACTIVE"
    assert states["INSPECTING"] == states["NORMALISING"] == "DONE"


