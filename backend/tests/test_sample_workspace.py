def test_the_sample_run_loads_every_file_in_the_workspace_folder(client):
    """Every export in the folder becomes a source, counted from disk.

    The folder is generated by a separate script and changes; the
    assertion is therefore against what is on disk at this moment, never
    against a remembered file list or count.
    """
    files = workspace_files()
    assert files, "no sample workspace on disk to test against"

    response = client.post("/runs/sample", json={})
    assert response.status_code == 200, response.text
    body = response.json()

    assert body["errors"] == [], body["errors"]
    assert body["source_count"] == len(files)
    assert {s["filename"] for s in body["sources"]} == {p.name for p in files}
    assert body["record_count"] == sum(s["row_count"] for s in body["sources"])
    assert body["record_count"] > 0

    # The POST /runs shape, so a caller can treat it as a created run.
    assert body["run_id"].startswith("run_")
    assert body["status"] == "DRAFT"
    assert body["label"]

    # And it is a real run in the store, with real sources behind it.
    stored = client.get(f"/runs/{body['run_id']}").json()
    assert len(stored["sources"]) == len(files)
    assert {s["filename"] for s in stored["sources"]} == {p.name for p in files}

    for source in body["sources"]:
        for field in ("detected_source_type", "detection_confidence", "row_count",
                      "needs_confirmation", "duplicate_of", "provider"):
            assert field in source, f"{source['filename']} is missing {field}"
        assert source["row_count"] > 0
        assert 0.0 <= source["detection_confidence"] <= 1.0


def test_sample_classification_equals_an_upload_of_the_same_bytes(client):
    """The sample is ingested, not injected.

    The cheap way to build this endpoint is to write source rows
    directly with a type taken from the filename. That would look
    identical until the day the classifier disagreed with the filename,
    which is exactly the day it matters. So every field the classifier
    produces is compared against the same file uploaded through
    /runs/{id}/sources — no expected values are written down here,
    because the folder's contents are not this test's to know.
    """
    files = workspace_files()
    assert files

    sample = client.post("/runs/sample", json={}).json()
    by_name = {s["filename"]: s for s in sample["sources"]}

    upload_run = client.post("/runs", json={"label": "control"}).json()["run_id"]
    for path in files:
        response = client.post(
            f"/runs/{upload_run}/sources",
            files=[("files", (path.name, path.read_bytes(), "application/octet-stream"))],
        )
        assert response.status_code == 200, response.text
        uploaded = response.json()["sources"][0]
        loaded = by_name[path.name]

        for field in ("detected_source_type", "detection_confidence", "provider",
                      "needs_confirmation", "source_type", "role", "suggested_role"):
            assert loaded[field] == uploaded[field], (
                f"{path.name}: sample reported {field}={loaded[field]!r}, "
                f"an upload of the same bytes reported {uploaded[field]!r}"
            )
        assert loaded["row_count"] == uploaded["detection"]["row_count"]
        assert loaded["role_confirmed"] == uploaded["role_confirmed"]


def test_a_duplicate_file_in_the_sample_is_flagged_exactly_as_an_upload_would_be(client):
    """Byte-identical files are reported, not hidden.

    Only asserted when the folder actually contains a duplicate — the
    folder is not this test's to arrange — but when it does, the second
    copy must point at the first by both id and filename.
    """
    sample = client.post("/runs/sample", json={}).json()
    by_id = {s["source_id"]: s for s in sample["sources"]}
    flagged = [s for s in sample["sources"] if s["duplicate_of"]]

    hashes = {}
    for path in workspace_files():
        import hashlib
        hashes.setdefault(hashlib.sha256(path.read_bytes()).hexdigest(), []).append(path.name)
    repeated = [names for names in hashes.values() if len(names) > 1]

    assert len(flagged) == sum(len(names) - 1 for names in repeated)
    for source in flagged:
        original = by_id[source["duplicate_of"]]
        assert source["duplicate_of_filename"] == original["filename"]
        assert source["filename"] != original["filename"]
    assert sample["duplicates"] == [
        {"filename": s["filename"], "duplicate_of_filename": s["duplicate_of_filename"]}
        for s in flagged
    ]


def test_a_sample_source_the_classifier_is_unsure_about_still_asks(client):
    """No auto-confirmation to smooth the demo.

    Whatever the folder holds, the invariant is the same: a source the
    classifier flagged is a source that has not been confirmed, and it
    is exactly the set of sources execution refuses to proceed on.
    """
    sample = client.post("/runs/sample", json={}).json()
    run_id = sample["run_id"]
    unsure = [s for s in sample["sources"] if s["needs_confirmation"]]

    for source in unsure:
        assert source["role_confirmed"] is False, (
            f"{source['filename']} was flagged for confirmation and confirmed anyway"
        )
    assert sample["needs_confirmation"] == [s["filename"] for s in unsure]

    execute = client.post(f"/runs/{run_id}/execute", json={})
    if unsure:
        assert execute.status_code == 400, execute.text
        detail = execute.json()["detail"]
        for source in unsure:
            assert source["filename"] in detail
    else:
        assert execute.status_code == 200, execute.text


