# The order the pipeline can legally move through. Used to assert that
# what a poller observes never goes backwards; DETERMINISTIC and
# INVESTIGATING are the same pass named for what it is currently doing,
# and it can only gain AI consultations, never lose them.
STAGE_ORDER = {
    "INSPECTING": 0, "NORMALISING": 1, "DETERMINISTIC": 2,
    "INVESTIGATING": 3, "REVIEW": 4, "COMPLETE": 5,
}


def workspace_files() -> list[Path]:
    return runs_api.sample_workspace_files()


def confirm_everything(client, run_id) -> None:
    """Answer the classifier's questions the way a person would.

    Confirms the type it already proposed — the point is that it asked,
    not that the answer differs.
    """
    sources = client.get(f"/runs/{run_id}").json()["sources"]
    updates = [
        {"source_id": s["source_id"], "source_type": s["source_type"],
         "role": s["role"], "confirmed": True}
        for s in sources
        if (s["detection"].get("classification") or {}).get("needs_confirmation")
    ]
    if updates:
        response = client.put(f"/runs/{run_id}/plan", json={"sources": updates, "confirmed": True})
        assert response.status_code == 200, response.text


