class StubModelVerifier:
    """A verifier that answers as a provider would, without a network.

    `backend` is the string a real chain writes — "provider:model" — so
    the records it produces are indistinguishable, to everything
    downstream, from records a live provider served. That is the point:
    the counting has to be driven by what is stored, not by what the
    process happens to know about its own configuration.
    """

    backend = "gemini:stub-model"

    def compare(self, comparison):
        from app.engine.semantic import SemanticVerdictResult

        return SemanticVerdictResult(
            verdict="AMBIGUOUS", confidence=0.4,
            rationale="stub verifier: deliberately undecided",
            backend=self.backend,
        )


def run_to_completion(client, run_id, timeout=180) -> list[dict]:
    """Poll /progress the way the UI does, keeping every snapshot."""
    seen = []
    deadline = time.time() + timeout
    while time.time() < deadline:
        progress = client.get(f"/runs/{run_id}/progress").json()
        seen.append(progress)
        if progress["complete"]:
            return seen
        time.sleep(0.05)
    raise AssertionError(f"run did not complete in time; last stage {seen[-1]['stage']}")


