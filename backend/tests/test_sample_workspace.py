"""
The one-click sample workspace, the pipeline-progress endpoint, and the
product-facing provider status.

Three things are pinned here, and all three are about the same failure:
showing a person something the backend did not actually establish.

  * `POST /runs/sample` must ingest the sample folder through the same
    path an upload takes. The way this goes wrong quietly is by
    shortcutting it — writing a source row with a hardcoded type, or
    quietly confirming a file the classifier was unsure about so the
    demo does not have to ask. So the sample's classification is
    asserted to equal what an upload of the same bytes produces, and
    nothing is asserted about *which* provider any file is: the folder
    is regenerated independently of this code, and a test that pins its
    contents would be pinning a snapshot rather than the behaviour.

  * `GET /runs/{id}/progress` must report where a run actually got to. A
    progress display is the easiest place in a product to put a number
    nobody computed, so the counts are checked against the records
    themselves, and a count that is not yet knowable is checked to be
    `null` rather than a zero that would render as a measurement.

  * `GET /ai/status` must never carry key material, and must say `null`
    rather than invent a "last successful request" it never observed.

Offline throughout: `ACCORD_AI_DISABLED=1`, so every outcome here is a
property of this code rather than of a network.
"""

